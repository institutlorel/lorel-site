// Dev-only belt-and-suspenders check for dynamic-key lookups (e.g. dict[key]
// patterns) that might resolve to undefined despite the compile-time guard
// above. No-ops in production.
export function warnIfMissing<T>(value: T, path: string): T {
  if (process.env.NODE_ENV !== "production" && (value === undefined || value === null)) {
    // eslint-disable-next-line no-console
    console.warn(`[i18n] Missing dictionary value at "${path}"`);
  }
  return value;
}
