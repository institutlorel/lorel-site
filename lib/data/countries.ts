export const DEFAULT_COUNTRY_ISO2 = "MA";

const COUNTRY_BY_ISO2 = new Map(COUNTRIES.map((c) => [c.iso2, c]));

export function getCountry(iso2: string): CountryDial {
  return COUNTRY_BY_ISO2.get(iso2) ?? COUNTRY_BY_ISO2.get(DEFAULT_COUNTRY_ISO2)!;
}

// Builds the full E.164-ish international number: dial code + local part, with
// spaces/dashes and a leading "0" (common in local-format entry) stripped.
export function toE164(iso2: string, localNumber: string): string {
  const country = getCountry(iso2);
  const cleaned = localNumber.replace(/[^\d]/g, "").replace(/^0+/, "");
  return `+${country.dial}${cleaned}`;
}

// Digit count of the local part only (dial code excluded) — used for length validation.
export function localDigitCount(localNumber: string): number {
  return localNumber.replace(/[^\d]/g, "").replace(/^0+/, "").length;
}
